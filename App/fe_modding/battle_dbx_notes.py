def note(path: str, key: str) -> str:
    """The English note for ``key`` in the table ``path``, or ''."""
    if path.endswith("zdbx/param.dbx") or path == "param.dbx":
        return PARAM_NOTES.get(key, "")
    return WIDGET_NOTES.get(key, "")
